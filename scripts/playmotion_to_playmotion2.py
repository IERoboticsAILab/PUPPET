#!/usr/bin/env python3
"""Convert PlayMotion (ROS 1) motions to PlayMotion2 (ROS 2) YAML.

Used by PUPPET (telepresence_motions.yaml -> ROS 2) and by the TIAGo demo-motion port (ROR-150,
from the Gallium rosparam dump). Plain Python + PyYAML, no ROS needed.

    scripts/playmotion_to_playmotion2.py IN.yaml [-o OUT.yaml] [--only extend,wave] [--rename open_gripper=open]

IN can be a PlayMotion motions file (`play_motion: motions: ...`), a full `rosparam dump`
(the `play_motion/motions` key is found), or a bare `motions:` mapping.

ROS 1:  name: {joints: [...], points: [{positions: [...], time_from_start: t}, ...], meta: {...}}
ROS 2:  name: {joints: [...], positions: [flat list], times_from_start: [...], meta: {...}}
Output is wrapped as `/**: ros__parameters: motions:`, the same layout as PAL's
tiago_bringup/config/motions/*.yaml, so it can be merged into play_motion2's parameters.
"""

import argparse
import sys

import yaml


def find_motions(doc):
    if not isinstance(doc, dict):
        raise ValueError("input is not a YAML mapping")
    if "play_motion" in doc and isinstance(doc["play_motion"], dict) and "motions" in doc["play_motion"]:
        return doc["play_motion"]["motions"]
    if "motions" in doc:
        return doc["motions"]
    raise ValueError("no play_motion/motions or motions key found")


def convert_motion(name, m):
    joints = list(m["joints"])
    positions, times = [], []
    last_t = -1.0
    for i, p in enumerate(m["points"]):
        pos = [float(x) for x in p["positions"]]
        if len(pos) != len(joints):
            raise ValueError(f"{name}: point {i} has {len(pos)} positions for {len(joints)} joints")
        t = float(p["time_from_start"])
        if t <= last_t:
            raise ValueError(f"{name}: time_from_start must increase (point {i}: {t} after {last_t})")
        last_t = t
        positions.extend(pos)
        times.append(t)
    out = {"joints": joints, "positions": positions, "times_from_start": times}
    meta = m.get("meta")
    if meta:
        out["meta"] = {k: meta[k] for k in ("name", "usage", "description") if k in meta}
    return out


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("input")
    ap.add_argument("-o", "--output", help="write here instead of stdout")
    ap.add_argument("--only", help="comma-separated motion names to keep")
    ap.add_argument("--rename", action="append", default=[], metavar="OLD=NEW")
    args = ap.parse_args(argv)

    with open(args.input) as f:
        motions = find_motions(yaml.safe_load(f))

    only = set(args.only.split(",")) if args.only else None
    renames = dict(r.split("=", 1) for r in args.rename)
    if only:
        missing = only - set(motions)
        if missing:
            sys.exit(f"error: not in {args.input}: {', '.join(sorted(missing))}")

    out = {}
    for name in sorted(motions):
        if only and name not in only:
            continue
        out[renames.get(name, name)] = convert_motion(name, motions[name])

    text = yaml.safe_dump({"/**": {"ros__parameters": {"motions": out}}}, sort_keys=False, default_flow_style=None, width=100)
    header = f"# Generated by scripts/playmotion_to_playmotion2.py from {args.input}. Do not edit by hand.\n"
    if args.output:
        with open(args.output, "w") as f:
            f.write(header + text)
        print(f"wrote {len(out)} motion(s) to {args.output}", file=sys.stderr)
    else:
        sys.stdout.write(header + text)


if __name__ == "__main__":
    main()
